"""Add photos to the website gallery.

Usage (from the repo root):
    python tools/add_photos.py "C:/path/to/folder/of/photos"
    python tools/add_photos.py            # just rebuild gallery/photos.js

For each JPG/PNG/WEBP (and HEIC if pillow-heif is installed) it:
  * fixes phone rotation (EXIF orientation),
  * saves a web-sized copy  -> gallery/photos/full/<name>.jpg   (max 2400px)
  * saves a thumbnail       -> gallery/photos/thumbs/<name>.jpg (800px wide)
  * strips GPS / camera metadata from the published copies.
Then it rewrites gallery/photos.js, ordered by when each photo was taken.
Delete a photo from both folders and re-run to remove it from the gallery.
"""
import hashlib
import json
import os
import re
import sys
from datetime import datetime

from PIL import Image, ImageOps

try:  # optional iPhone HEIC support: pip install pillow-heif
    from pillow_heif import register_heif_opener
    register_heif_opener()
    EXTS = {".jpg", ".jpeg", ".png", ".webp", ".heic", ".heif"}
except ImportError:
    EXTS = {".jpg", ".jpeg", ".png", ".webp"}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FULL = os.path.join(ROOT, "gallery", "photos", "full")
THUMBS = os.path.join(ROOT, "gallery", "photos", "thumbs")
ORDER = os.path.join(ROOT, "gallery", "photos", "order.json")  # name -> taken timestamp
OUT_JS = os.path.join(ROOT, "gallery", "photos.js")

FULL_MAX = 2400
THUMB_W = 800


def slug(name):
    s = re.sub(r"[^a-z0-9]+", "-", os.path.splitext(name)[0].lower()).strip("-")
    return s or "photo"


def taken(im, path):
    try:
        exif = im.getexif()
        raw = exif.get_ifd(0x8769).get(36867) or exif.get(306)  # DateTimeOriginal / DateTime
        if raw:
            return datetime.strptime(str(raw).strip("\x00 "), "%Y:%m:%d %H:%M:%S").timestamp()
    except Exception:
        pass
    return os.path.getmtime(path)


def add(src_dir, order):
    os.makedirs(FULL, exist_ok=True)
    os.makedirs(THUMBS, exist_ok=True)
    files = sorted(f for f in os.listdir(src_dir) if os.path.splitext(f)[1].lower() in EXTS)
    skipped = [f for f in os.listdir(src_dir) if os.path.splitext(f)[1].lower() in {".heic", ".heif"} and f not in files]
    for f in files:
        path = os.path.join(src_dir, f)
        # name + short content hash: re-adding the same photo overwrites it,
        # two different photos with the same name (IMG_0001.jpg) both survive
        with open(path, "rb") as fh:
            digest = hashlib.sha1(fh.read()).hexdigest()[:6]
        out = "%s-%s.jpg" % (slug(f)[:50], digest)
        try:
            im = Image.open(path)
            when = taken(im, path)
            im = ImageOps.exif_transpose(im).convert("RGB")
        except Exception as e:
            print("  skip", f, "-", e)
            continue
        full = im.copy()
        full.thumbnail((FULL_MAX, FULL_MAX), Image.LANCZOS)
        full.save(os.path.join(FULL, out), "JPEG", quality=85, optimize=True, progressive=True)
        th = im.copy()
        th.thumbnail((THUMB_W, THUMB_W * 3), Image.LANCZOS)
        th.save(os.path.join(THUMBS, out), "JPEG", quality=78, optimize=True, progressive=True)
        order[out] = {"taken": when}
        print("  added", f, "->", out)
    if skipped:
        print("\nSkipped %d HEIC file(s). Run `pip install pillow-heif` and re-run to include them." % len(skipped))


def build(order):
    names = [f for f in os.listdir(FULL) if f.endswith(".jpg") and os.path.exists(os.path.join(THUMBS, f))] if os.path.isdir(FULL) else []
    names.sort(key=lambda f: (order.get(f, {}).get("taken", 0), f))
    items = []
    for f in names:
        with Image.open(os.path.join(THUMBS, f)) as t:
            w, h = t.size
        items.append({"thumb": "photos/thumbs/" + f, "full": "photos/full/" + f, "w": w, "h": h, "alt": ""})
    with open(OUT_JS, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/add_photos.py — run that script to update this list.\n")
        fh.write("window.GALLERY_PHOTOS = " + json.dumps(items, indent=1) + ";\n")
    # keep only entries for photos that still exist; don't store local source paths
    with open(ORDER, "w", encoding="utf-8") as fh:
        json.dump({f: {"taken": order.get(f, {}).get("taken", 0)} for f in names}, fh, indent=1)
    print("\nGallery now has %d photo(s)." % len(items))


if __name__ == "__main__":
    order = {}
    if os.path.exists(ORDER):
        with open(ORDER, encoding="utf-8") as fh:
            order = json.load(fh)
    if len(sys.argv) > 1:
        add(sys.argv[1], order)
    build(order)
